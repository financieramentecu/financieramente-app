/**
 * Parámetros para registrar un log de auditoría
 */
export interface AuditLogParams {
	userId?: number
	roleId?: number
	action: AuditAction
	email?: string
	ipAddress?: string
	userAgent?: string
	details?: string
}

/**
 * Registra un evento en el log de auditoría
 */
export async function logAuditEvent(params: AuditLogParams): Promise<void> {
	try {
		await prisma.auditLog.create({
			data: {
				idUser: params.userId,
				idRole: params.roleId,
				action: params.action,
				email: params.email,
				ipAddress: params.ipAddress,
				userAgent: params.userAgent,
				details: params.details,
			},
		})
	} catch (error) {
		// No lanzar error para no interrumpir el flujo de autenticación
		// Solo registrar en consola para debugging
		console.error('Error logging audit event:', error)
	}
}

/**
 * Client IP for audit records. Uses the trusted source (nginx `x-real-ip`, else
 * the LAST `x-forwarded-for` hop): the first hop is client controlled.
 */
export function getClientIp(headers: Headers): string | undefined {
	return resolveTrustedClientIp(headers)
}

/**
 * Obtiene el User-Agent desde headers
 */
export function getUserAgent(headers: Headers): string | undefined {
	return headers.get('user-agent') || undefined
}
